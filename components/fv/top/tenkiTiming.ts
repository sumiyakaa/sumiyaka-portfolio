/**
 * 転記（てんき）— トップ FV の時間軸（秒）
 *
 * ステージ時計 t=0 ＝「マウント直後の最初の rAF」。★書体の読込も版下の焼き付けも
 * 待たない（散らばり〜一本化は題字の版下を必要としないため）。版下は並行して焼き、
 * writeStart までに間に合えばそのまま進む。間に合わなければ writeStart で時計を
 * 止めて「一本化した線」の状態で待ち、版下が焼けたら続きから進む（holdMax が上限）。
 * 画面外・背面タブでは時計ごと止まる。
 *
 *   0            散らばり … 事務のデータの断片（CSV / XLSX / PDF）が角度も大きさも
 *                ばらばらに漂う（＝バラバラな事務作業）
 *   alignStart   整列 … 誰も触らないのに回転が戻り、水平に揃って一列の帯になる。
 *                断片の中の行が左右へ伸び、隣の断片と端で繋がる（＝繋がっていない
 *                ものが繋がる）
 *   collapseStart 一本化 … 帯が 1 本の細い白線に潰れる
 *   writeStart   筆 … その線が左端から題字へ流れ込み、字画を書き上げる。
 *                書かれた側から DOM の文字が letterFade 秒でクロスフェードして現れ、
 *                版下側は同じだけ薄れる（＝題字の上には何も残らない）
 *   settle       定着 … 墨の一滴が落ちて背景に滲み（流体の起動）、灯が一点ともる。
 *                他要素（肩書き／サブ／宣言／隅）の入場が始まる
 *
 * 末尾の文字が読める時刻 ≒ writeStart + writeDur + letterFade = 1.53s（< 1.8s）
 */
export const TENKI_T = {
  /** ステージの不透明度が立ち上がる時間（CSS 側の .stage も 0.5s に揃えてある） */
  fadeIn: 0.24,
  /** 整列の開始・所要 */
  alignStart: 0.36,
  alignDur: 0.44,
  /** 一本化の開始・所要 */
  collapseStart: 0.8,
  collapseDur: 0.17,
  /** 筆の掃引の開始・所要（3 行ぶんの合計） */
  writeStart: 0.97,
  writeDur: 0.4,
  /** 掃引時間のうち「行から行への返し」に充てる割合 */
  returnShare: 0.14,
  /** DOM の文字がクロスフェードする時間（版下が薄れる時間でもある） */
  letterFade: 0.16,
  /** 書き終えたあと筆先が消えるまで */
  brushOut: 0.12,
  /** 墨の一滴が落ちる時間（settle の手前） */
  dropFall: 0.18,
  /** 定着＝灯がともり、墨が滲み、他要素が入場する */
  settle: 1.51,
  /** 版下が間に合わないとき、一本化した線のまま待てる上限（秒）。
   *  これを超えたら筆を省いて題字を出し、定着へ進む（読めない状態で止まらない保険）。 */
  holdMax: 1.2,
  /** 何があっても DOM の題字を出す壁時計の上限（rAF 停止などの最終保険） */
  hardDeadline: 2.6,
} as const;

