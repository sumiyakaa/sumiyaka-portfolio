/* ------------------------------------------------------------------ *
 * 正規表現の組み立て
 * ------------------------------------------------------------------ */

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** 長いものから順に並べた選択肢。JS の選択は左から試すので、この並びが「最長一致」になる */
function alternation(words: readonly string[]): string {
  return [...words]
    .sort((a, b) => b.length - a.length)
    .map(escapeRe)
    .join("|");
}

const KANJI_FORM_RE = new RegExp(alternation(KANJI_CORPORATE_FORMS), "g");
const KANA_FORM_RE = new RegExp(alternation(KANA_CORPORATE_FORMS), "g");

const ABBR = alternation([...KANA_ABBREVIATIONS, ...KANJI_ABBREVIATIONS]);
/** 中間形 `(カ)` … どこにあっても消す */
const ABBR_MIDDLE_RE = new RegExp(`\\((?:${ABBR})\\)`, "g");
/** 前株 `カ)◯◯` … 先頭だけ */
const ABBR_HEAD_RE = new RegExp(`^(?:${ABBR})\\)`);
/** 後株 `◯◯(カ` … 末尾だけ */
const ABBR_TAIL_RE = new RegExp(`\\((?:${ABBR})$`);

const KIND_HEAD_RE = new RegExp(`^(?:${alternation(TRANSACTION_KINDS)})`, "i");

/**
 * 末尾の閉じた括弧グループ。中身が数字・英字・「明細番号」「No」「番」「#」だけなら落とす。
 * ゆうちょの `（明細番号０００１番）` を想定している。
 * ⚠ 閉じていない `(カ` は対象外なので、後株の表記を壊さない。
 */
const TRAILING_REF_RE = /[(（]\s*(?:明細番号|明細|No\.?|NO\.?|#)?\s*[0-9A-Za-z]*\s*(?:番|号)?\s*[)）]\s*$/i;

/** 小書きカナ → 大文字カナ。全銀は小文字を使えず大文字へ変換されるため、必ず揃える */
const SMALL_KANA_MAP: Record<string, string> = {
  ァ: "ア", ィ: "イ", ゥ: "ウ", ェ: "エ", ォ: "オ",
  ッ: "ツ", ャ: "ヤ", ュ: "ユ", ョ: "ヨ", ヮ: "ワ", ヵ: "カ", ヶ: "ケ",
  // ひらがなの小書きもここで潰す。ひらがな→カタカナ変換（手順7）は
  // 大文字・小文字を区別せず +0x60 するだけなので、先に潰しておかないと
  // 「しょうじ」だけが小書きのまま残って当たらなくなる。
  ぁ: "あ", ぃ: "い", ぅ: "う", ぇ: "え", ぉ: "お",
  っ: "つ", ゃ: "や", ゅ: "ゆ", ょ: "よ", ゎ: "わ", ゕ: "か", ゖ: "け",
};
const SMALL_KANA_RE = /[ァィゥェォッャュョヮヵヶぁぃぅぇぉっゃゅょゎゕゖ]/g;

/**
 * 長音とハイフンの類。全銀では長音が使えず、抜けたり `-` になったりする。
 * U+2014（—）は U+2015（―）と見分けがつかないので同じ扱いにする。
 */
const DASH_RE = /[ー‐\-―—–−_]/g;

/** 記号と空白。濁点・半濁点は落とさない（ガ と カ は別会社になりうる） */
const SYMBOL_RE = /[\s　・．.,、()（）「」/:'+\\]/g;

/* ------------------------------------------------------------------ *
 * 照合キー
 * ------------------------------------------------------------------ */

/**
 * 振込名義・取引先名 → 照合キー。
 *
 * **手順の順序に意味がある。入れ替えないこと。**
 * 括弧つきの略号（手順5）は、記号を消す手順9より前でなければ当たらない。
 */
export function normalizeMatchKey(raw: string): string {
  if (!raw) return "";

  // 1. 前後の空白を落とす
  // 2. Unicode NFKC 正規化（半角カナ→全角カナ・濁点の結合・全角英数→半角・㈱→(株)）
  const base = raw.trim().normalize("NFKC");
  let s = base;

  // 3. 漢字の法人格を消す
  s = s.replace(KANJI_FORM_RE, "");
  // 4. カナ表記の法人格（全形）を消す
  s = s.replace(KANA_FORM_RE, "");
  // 5. カナ略号を括弧つきで消す（中間 → 前株 → 後株）
  s = s.replace(ABBR_MIDDLE_RE, "");
  s = s.replace(ABBR_HEAD_RE, "");
  s = s.replace(ABBR_TAIL_RE, "");
  // 6. 小さいカナを大きいカナへ
  s = s.replace(SMALL_KANA_RE, (c) => SMALL_KANA_MAP[c] ?? c);
  // 7. ひらがな → カタカナ
  s = s.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60));
  // 8. 長音・ハイフンを消す
  s = s.replace(DASH_RE, "");
  // 9. 記号と空白を消す
  s = s.replace(SYMBOL_RE, "");
  // 10. 英字を大文字に
  s = s.toUpperCase();

  // 11. 空になったら戻す（`カ)` だけの名義を空文字にして全件一致させない）
  if (s === "") return base.replace(/[\s　]/g, "");
  return s;
}

/* ------------------------------------------------------------------ *
 * 摘要 → 振込依頼人名
 * ------------------------------------------------------------------ */

/**
 * 摘要の文字列から、振込依頼人とみられる部分を取り出す。
 *
 * ⚠ **落とせなくても失敗にしない。** 余計な語が残れば照合が当たらず「要確認」に落ちるだけ。
 *    推測で削りにいくと、別会社の入金を静かに消し込むほうへ倒れる。
 */
export function extractPayer(raw: string): string {
  if (!raw) return "";

  // 1. NFKC 正規化して trim
  const base = raw.normalize("NFKC").trim();
  let s = base;

  // 2. 末尾の参照番号（ゆうちょの「（明細番号０００１番）」など）を落とす
  s = s.replace(TRAILING_REF_RE, "").trim();

  // 3. 先頭の取引種別を1回だけ落とす
  s = s.replace(KIND_HEAD_RE, "");

  // 4. 残った先頭の区切りを落とす
  s = s.replace(/^[\s　\-‐―—–−:：]+/, "").trim();

  // 5. 空になったら手順2の結果を返す（「振込」だけの摘要を空にしない）
  if (s === "") return base.replace(TRAILING_REF_RE, "").trim();
  return s;
}
