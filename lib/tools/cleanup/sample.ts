/**
 * 元の Excel で**数値型として保存されていた**セル（`"行,列"`／どちらも0始まり）。
 *
 * `"1,5"` ＝ No.2 の郵便番号（`1000001`）。ハイフン無しで数値として保存された郵便番号は、
 * 先頭が 0 の地域だとその 0 が**読み込む前に失われる**。復元は原理的に不可能なので、
 * 直さず `numericStoredCode` として知らせるだけにする（計画書 §7-3）。
 */
const SAMPLE_NUMERIC_CELLS: readonly string[] = ["1,5"];

/**
 * 画面の初期表示に使うサンプル。
 * ⚠ 呼ぶたびに**新しい配列**を作る（UI が列の役割を書き換えても、次に読み直せば元へ戻る）。
 */
export function sampleParseResult(): ParseResult {
  const headers = [...SAMPLE_HEADERS];

  const columns: ColumnSpec[] = SAMPLE_HEADERS.map((header, index) => ({
    index,
    header,
    role: SAMPLE_ROLES[index] ?? "skip",
    guessed: true,
  }));

  const rows: NameRow[] = SAMPLE_CELLS.map((cells, index) => ({
    cells: [...cells],
    // 1行目が見出しなので、本文は2行目から
    sourceLine: SAMPLE_HEADER_LINE + 1 + index,
  }));

  return {
    headers,
    columns,
    rows,
    issues: [],
    sourceName: SAMPLE_FILE_NAME,
    sheetName: SAMPLE_SHEET_NAME,
    headerLine: SAMPLE_HEADER_LINE,
    numericCells: new Set<string>(SAMPLE_NUMERIC_CELLS),
  };
}
